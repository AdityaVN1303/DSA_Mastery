// Intersection of Two Sorted Arrays II

// Approaches

// Using Map / Set
// TC - O((N+M)log(N+M))
// SC - O(N + M)

// Using Merge (Independent Two Pointers Approach)
// TC - O(N + M)
// SC - O(N + M)

// Binary Search (If One of Two Arrays is significantly Smaller than other)
// TC - O(NlogM)
// SC - O(1)

// Use STL set_intersection (also unique and erase for deduplication)
// back_inserter used
// TC - O(N + M)
// SC - O(1)